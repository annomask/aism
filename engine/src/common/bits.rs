// UintSize is the size of a uint in bits.
const UINT_SIZE: isize = 32 << (!(0usize) >> 32 & 1); // 32 or 64

// /// LeadingZeros returns the number of leading zero bits in x; the result is UINT_SIZE for x == 0.
// pub fn leading_zeros(x: usize) -> isize { return UINT_SIZE - len(x) }

/// LeadingZeros8 returns the number of leading zero bits in x; the result is 8 for x == 0.
pub fn leading_zeros_8(x: u8) -> i32 {
    8 - len8(x)
}

/// LeadingZeros16 returns the number of leading zero bits in x; the result is 16 for x == 0.
pub fn leading_zeros_16(x: u16) -> i32 {
    16 - len16(x)
}

/// LeadingZeros32 returns the number of leading zero bits in x; the result is 32 for x == 0.
pub fn leading_zeros_32(x: u32) -> i32 {
    32 - len32(x)
}

/// LeadingZeros64 returns the number of leading zero bits in x; the result is 64 for x == 0.
pub fn leading_zeros_64(x: u64) -> i32 {
    64 - len64(x)
}

